import { format } from "prettier";
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

// Bundle SQL as TypeScript so Metro and the Node test runner use exactly the
// same migrations, without runtime filesystem access or a Babel SQL loader.
const journal = JSON.parse(readFileSync("drizzle/meta/_journal.json", "utf8"));
const migrations = journal.entries.map((entry) => {
  const query = readFileSync(`drizzle/${entry.tag}.sql`, "utf8");
  return {
    sql: query.split("--> statement-breakpoint"),
    bps: entry.breakpoints,
    folderMillis: entry.when,
    hash: createHash("sha256").update(query).digest("hex"),
  };
});
const output = await format(
  `// Generated by yarn db:generate. Do not edit.\nexport const migrations = ${JSON.stringify(migrations, null, 2)};\n`,
  { parser: "typescript" },
);
const path = "src/storage/migrations.ts";
if (process.argv.includes("--check")) {
  if (readFileSync(path, "utf8") !== output)
    throw new Error("Migration bundle is stale. Run yarn db:generate.");
} else writeFileSync(path, output);
